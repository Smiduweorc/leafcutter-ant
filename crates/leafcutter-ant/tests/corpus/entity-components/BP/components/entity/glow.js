export default defineComponent(({ name, template, schema }) => {
	name('demo:glow')
	schema({ type: 'number' })
	template((level = 1, { create, animation, animationController, location, identifier, projectNamespace, onActivated, onDeactivated, lootTable, tradeTable, spawnRule, client, mode, sourceEntity }) => {
		create({ 'minecraft:light': { level, at: location, id: identifier, ns: projectNamespace, mode } })
		create({ 'minecraft:type_family': { family: ['glowing'] } }, 'minecraft:entity/components')
		create({ group: { 'minecraft:scale': { value: 2 } } }, 'minecraft:entity/component_groups')
		animation({ loop: true, timeline: { '0.0': ['/say glow'] } }, 'q.is_alive')
		animation({ loop: false, timeline: { '1.0': ['/say once'] } })
		animation({ timeline: {} }, false)
		animation(null)
		animationController({ initial_state: 'a', states: { a: { on_entry: ['/say a'] } } }, 'q.is_baby')
		onActivated({ run_command: { command: ['say on'] } })
		onDeactivated({ run_command: { command: ['say off'] } })
		const loot = lootTable({ pools: [{ rolls: 1, entries: [{ type: 'item', name: 'minecraft:glowstone' }] }] })
		create({ 'minecraft:loot': { table: loot } }, 'minecraft:entity/components')
		tradeTable({ tiers: [] })
		spawnRule({ format_version: '1.8.0', 'minecraft:spawn_rules': { description: { identifier } } })
		client.create({ textures: { default: 'textures/entity/glow' } })
		create({ copied: Object.keys(sourceEntity()['minecraft:entity']) }, 'minecraft:entity/description/custom')
	})
})
